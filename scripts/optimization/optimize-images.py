"""Reproducible lossless web derivatives. Originals and native frame sources are retained.
Pillow 12.3.0 / libwebp 1.6.0. build writes derivatives; verify decodes every pair.
benchmark writes experiments only under .codex-tmp, never production references.
"""
import argparse, hashlib, io, json, re, time
from pathlib import Path
from PIL import Image, ImageChops, features

ROOT=Path(__file__).resolve().parents[2]
APP=ROOT/'apps/mobile'
REGISTRY=APP/'components/branding/baya/frameSources.ts'
MANIFEST=ROOT/'scripts/optimization/mascot-derivatives.json'
DOC=ROOT/'docs/optimization'

def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()
def encode(im,fmt,**options):
    b=io.BytesIO();im.save(b,format=fmt,**options);return b.getvalue()
def pairs():
    for ref in re.findall(r"require\('([^']+\.png)'\)",REGISTRY.read_text()):
        source=(REGISTRY.parent/ref).resolve()
        target=Path(str(source).replace('branding\\baya\\','branding\\baya-web\\').replace('branding/baya/','branding/baya-web/')).with_suffix('.webp')
        assert APP/'assets/branding/baya-web' in target.parents
        yield ref,source,target

def build():
    rows=[]; web=REGISTRY.read_text(encoding='utf-8')
    for ref,source,target in pairs():
        with Image.open(source) as original:
            im=original.convert('RGBA');data=encode(im,'WEBP',lossless=True,exact=True,method=6)
            assert Image.open(io.BytesIO(data)).convert('RGBA').tobytes()==im.tobytes()
            assert len(data)<source.stat().st_size
            target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data)
            rows.append(dict(source=source.relative_to(ROOT).as_posix(),output=target.relative_to(ROOT).as_posix(),source_sha256=sha(source),output_sha256=sha(target),original_bytes=source.stat().st_size,optimized_bytes=len(data),width=im.width,height=im.height,pixel_identical=True))
        web=web.replace(ref,ref.replace('/baya/','/baya-web/').replace('.png','.webp'))
    REGISTRY.with_suffix('.web.ts').write_text('// Generated by scripts/optimization/optimize-images.py build; edit frameSources.ts.\n'+web,encoding='utf-8')
    MANIFEST.write_text(json.dumps(dict(policy='lossless, exact RGBA, original dimensions; web only',pillow=Image.__version__,libwebp=features.version('webp'),frames=rows),indent=2)+'\n',encoding='utf-8')
    print('Generated',len(rows),'frames;',sum(r['original_bytes']-r['optimized_bytes'] for r in rows),'bytes saved')

def verify():
    rows=json.loads(MANIFEST.read_text())['frames']
    canonical=json.loads((APP/'assets/branding/baya/animations/v1.1/manifest.json').read_text())
    assert len(rows)==len(list(pairs()))==sum(s['frameCount'] for s in canonical['sequences'].values())
    for row in rows:
        src=ROOT/row['source'];dst=ROOT/row['output']
        assert sha(src)==row['source_sha256'] and sha(dst)==row['output_sha256']
        with Image.open(src) as a,Image.open(dst) as b:
            assert a.size==b.size and a.convert('RGBA').tobytes()==b.convert('RGBA').tobytes()
    print('Verified',len(rows),'RGBA frames, dimensions and source/output hashes')

def benchmark():
    results=[]
    samples=[APP/'assets/branding/baya/animations/v1.1/blink/frame-000.png',APP/'assets/illustrations/baybayin/gavino/ba.png',APP/'assets/illustrations/baybayin/guides-1024/be_bi.png',*sorted((APP/'assets/storybook').rglob('*.jpg'))]
    for p in samples:
        with Image.open(p) as original:
            im=original.convert('RGBA')
            for fmt,opts in [('PNG',dict(optimize=True)),('WEBP',dict(lossless=True,exact=True,method=6)),('WEBP',dict(quality=85,method=6)),('AVIF',dict(quality=85,speed=6))]:
                start=time.perf_counter();b=encode(im,fmt,**opts);decoded=Image.open(io.BytesIO(b)).convert('RGBA')
                results.append(dict(source=p.relative_to(ROOT).as_posix(),original_bytes=p.stat().st_size,format=fmt,settings=opts,bytes=len(b),encode_ms=(time.perf_counter()-start)*1000,pixel_identical=im.tobytes()==decoded.tobytes(),deployed=False))
    # Packing and temporal encoding are experiments; same frame cadence and full dimensions.
    for state,folder in [('wave','animations/v1.1/wave'),('blink','animations/v1.1/blink')]:
        frames=[Image.open(p).convert('RGBA') for p in sorted((APP/'assets/branding/baya'/folder).glob('*.png'))]
        sheet=Image.new('RGBA',(frames[0].width*5,frames[0].height*5))
        for i,im in enumerate(frames):sheet.paste(im,((i%5)*im.width,(i//5)*im.height))
        for kind,im,opts in [('sprite',sheet,{}),('animated-webp',frames[0],dict(save_all=True,append_images=frames[1:],duration=60,loop=0))]:
            start=time.perf_counter();b=encode(im,'WEBP',lossless=True,exact=True,method=6,**opts)
            results.append(dict(state=state,format=kind,bytes=len(b),decoded_canvas_bytes=im.width*im.height*4,encode_ms=(time.perf_counter()-start)*1000,deployed=False,decision='retain frame renderer: preserves rest/phase/reduced-motion controls and independent frame decode; no renderer migration without native/browser timing validation'))
    (DOC/'image-format-benchmarks.json').write_text(json.dumps(results,indent=2),encoding='utf-8')
    print('Benchmarked',len(results),'format candidates')

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('action',choices=['build','verify','benchmark']);args=ap.parse_args()
    {'build':build,'verify':verify,'benchmark':benchmark}[args.action]()
