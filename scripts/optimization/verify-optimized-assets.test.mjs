import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { verifyOptimizedAssets } from '../../apps/mobile/scripts/verify-optimized-assets.mjs';

test('production sources and generated web registry pass the build gate', async () => {
  assert.equal(await verifyOptimizedAssets(), 50);
});

test('gate rejects stale sources, derivative bytes and generated mappings', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'baya-asset-gate-'));
  const digest = bytes => createHash('sha256').update(bytes).digest('hex');
  const frames = [];
  let canonical = '';
  const write = async (file, data) => {
    const target = path.join(root, file);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, data);
  };
  try {
    const sequence = {frameCount: 7, frames: []};
    for (let i = 0; i < sequence.frameCount; i++) {
      const name = `frame-${String(i).padStart(3, '0')}.png`;
      sequence.frames.push({index: i, file: name});
      const source = `apps/mobile/assets/branding/baya/animations/v1.1/blink/${name}`;
      const output = source.replace('/baya/', '/baya-web/').replace('.png', '.webp');
      const bytes = Buffer.from(`frame-${i}`);
      await write(source, bytes); await write(output, bytes);
      frames.push({ source, output, source_sha256: digest(bytes), output_sha256: digest(bytes) });
      canonical += `require('../../../assets/branding/baya/animations/v1.1/blink/${name}');\n`;
    }
    const registry = 'apps/mobile/components/branding/baya/frameSources';
    const web = '// Generated by scripts/optimization/optimize-images.py build; edit frameSources.ts.\n' + canonical.replaceAll('/baya/', '/baya-web/').replaceAll('.png', '.webp');
    await write(registry + '.ts', canonical); await write(registry + '.web.ts', web);
    await write('scripts/optimization/mascot-derivatives.json', JSON.stringify({ frames }));
    await write('apps/mobile/assets/branding/baya/animations/v1.1/manifest.json', JSON.stringify({version: 'v1.1', sequences: {blink: sequence}}));
    assert.equal(await verifyOptimizedAssets(root), 7);
    for (const file of [frames[0].source, frames[0].output, registry + '.web.ts']) {
      const original = await readFile(path.join(root, file));
      await write(file, 'corrupted');
      await assert.rejects(verifyOptimizedAssets(root), /Stale|stale/);
      await write(file, original);
    }
    frames[0].output = '../outside.webp';
    await write('scripts/optimization/mascot-derivatives.json', JSON.stringify({ frames }));
    await assert.rejects(verifyOptimizedAssets(root), /Invalid derivative mapping/);
  } finally {
    assert(path.dirname(root) === path.resolve(tmpdir()) && path.basename(root).startsWith('baya-asset-gate-'));
    await rm(root, { recursive: true });
  }
});
