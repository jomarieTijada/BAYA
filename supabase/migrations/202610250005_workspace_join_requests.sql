-- Preserve all existing memberships. New membership requires owner approval.
begin;
create table public.workspace_join_requests (
 request_id uuid primary key default gen_random_uuid(),
 workspace_id uuid not null references public.workspaces on delete cascade,
 learner_profile_id uuid not null references public.profiles on delete cascade,
 status text not null default 'pending' check(status in ('pending','approved','rejected')),
 requested_at timestamptz not null default now(),
 reviewed_at timestamptz,
 reviewed_by uuid references public.mentor_profiles on delete restrict,
 check (reviewed_at is null or reviewed_at >= requested_at),
 check ((status='pending' and reviewed_at is null and reviewed_by is null)
     or (status<>'pending' and reviewed_at is not null and reviewed_by is not null))
);
create unique index one_pending_workspace_request on public.workspace_join_requests(learner_profile_id,workspace_id) where status='pending';
create index workspace_pending_requests on public.workspace_join_requests(workspace_id,requested_at) where status='pending';
alter table public.workspace_join_requests enable row level security;
revoke all on public.workspace_join_requests from public,anon,authenticated;
grant select on public.workspace_join_requests to authenticated;
create policy authorized_requests on public.workspace_join_requests for select to authenticated
 using(learner_profile_id=baya_private.own_profile() or baya_private.owns_workspace(workspace_id));

-- Minimal review context. The request reference is generated by the server;
-- mentors should compare it with the learner's screen, not trust a name alone.
create function baya_private.join_request_json(r public.workspace_join_requests) returns jsonb
 language sql stable security definer set search_path='' as $$
 select to_jsonb(r)||jsonb_build_object('display_name',p.display_name,'workspace_name',w.workspace_name)
 from public.profiles p,public.workspaces w where p.profile_id=r.learner_profile_id and w.workspace_id=r.workspace_id
$$;
revoke all on function baya_private.join_request_json(public.workspace_join_requests) from public,anon,authenticated;

create function public.request_workspace_join(p_code text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare p uuid:=baya_private.own_profile(); w public.workspaces; r public.workspace_join_requests; m public.workspace_memberships;
begin
 if p is null or not exists(select 1 from public.profiles where profile_id=p and role='learner') then raise exception 'unauthorized' using errcode='42501'; end if;
 if p_code is null or upper(btrim(p_code)) !~ '^BAYA-[A-F0-9]{12}$' then raise exception 'invalid_code' using errcode='22023'; end if;
 select * into w from public.workspaces where workspace_code=upper(btrim(p_code)) for share;
 if not found then raise exception 'invalid_code' using errcode='22023'; end if;
 if w.status<>'active' then raise exception 'inactive' using errcode='P0001'; end if;
 -- Serialize submissions for this identity, including retries after a timeout.
 perform 1 from public.profiles where profile_id=p for update;
 select * into m from public.workspace_memberships where workspace_id=w.workspace_id and learner_profile_id=p and is_active;
 if found then return jsonb_build_object('kind','already_member','joined',jsonb_build_object('workspace',to_jsonb(w),'membership',to_jsonb(m),'alreadyJoined',true)); end if;
 select * into r from public.workspace_join_requests where workspace_id=w.workspace_id and learner_profile_id=p and status='pending';
 if found then return jsonb_build_object('kind','already_pending','request',baya_private.join_request_json(r)); end if;
 insert into public.workspace_join_requests(workspace_id,learner_profile_id) values(w.workspace_id,p) returning * into r;
 return jsonb_build_object('kind','request_submitted','request',baya_private.join_request_json(r));
end $$;

create function public.list_my_join_requests() returns jsonb
language plpgsql stable security definer set search_path='' as $$
declare p uuid:=baya_private.own_profile();
begin
 if p is null or not exists(select 1 from public.profiles where profile_id=p and role='learner') then raise exception 'unauthorized' using errcode='42501'; end if;
 return (select coalesce(jsonb_agg(baya_private.join_request_json(r) order by r.requested_at desc),'[]'::jsonb) from public.workspace_join_requests r where r.learner_profile_id=p);
end $$;
create function public.list_workspace_join_requests(p_workspace_id uuid) returns jsonb
language plpgsql stable security definer set search_path='' as $$
begin
 if not baya_private.owns_workspace(p_workspace_id) then raise exception 'unauthorized' using errcode='42501'; end if;
 return (select coalesce(jsonb_agg(baya_private.join_request_json(r) order by r.requested_at,r.request_id),'[]'::jsonb) from public.workspace_join_requests r where r.workspace_id=p_workspace_id and r.status='pending');
end $$;

create function public.review_workspace_join_request(p_request_id uuid,p_decision text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare r public.workspace_join_requests; w public.workspaces; m public.workspace_memberships; reviewer uuid:=baya_private.own_mentor();
begin
 if reviewer is null then raise exception 'unauthorized' using errcode='42501'; end if;
 if p_decision is null or p_decision not in ('approved','rejected') then raise exception 'invalid_decision' using errcode='22023'; end if;
 -- Check ownership before locking or exposing the request.
 select w0.* into w from public.workspaces w0 join public.workspace_join_requests r0 using(workspace_id)
 where r0.request_id=p_request_id and w0.mentor_profile_id=reviewer for share of w0;
 if not found then raise exception 'unauthorized' using errcode='42501'; end if;
 select * into r from public.workspace_join_requests where request_id=p_request_id for update;
 if r.status<> 'pending' and r.status<>p_decision then raise exception 'already_processed' using errcode='40001'; end if;
 if r.status='pending' then
  if p_decision='approved' then
   if w.status<>'active' then raise exception 'inactive' using errcode='P0001'; end if;
   if not exists(select 1 from public.profiles where profile_id=r.learner_profile_id and role='learner') then raise exception 'unauthorized' using errcode='42501'; end if;
   insert into public.workspace_memberships(workspace_id,learner_profile_id) values(r.workspace_id,r.learner_profile_id)
   on conflict(learner_profile_id,workspace_id) do update set is_active=true;
  end if;
  update public.workspace_join_requests set status=p_decision,reviewed_at=now(),reviewed_by=reviewer where request_id=r.request_id returning * into r;
 end if;
 select * into m from public.workspace_memberships where workspace_id=r.workspace_id and learner_profile_id=r.learner_profile_id;
 return jsonb_build_object('request',baya_private.join_request_json(r),'membership',case when m.membership_id is null then null else to_jsonb(m) end);
end $$;

-- Close the legacy instant-join path. Old clients may only read an existing membership.
create or replace function public.join_workspace(p_code text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare result jsonb;
begin
 result:=public.request_workspace_join(p_code);
 if result->>'kind'<>'already_member' then raise exception 'mentor_approval_required' using errcode='42501'; end if;
 return result->'joined';
end $$;

create or replace function public.list_owned_workspaces() returns jsonb language plpgsql stable security definer set search_path='' as $$
declare m uuid:=baya_private.own_mentor();
begin
 if m is null then raise exception 'unauthorized' using errcode='42501'; end if;
 return (select coalesce(jsonb_agg(to_jsonb(w)||jsonb_build_object(
 'learnerCount',(select count(*) from public.workspace_memberships wm where wm.workspace_id=w.workspace_id and wm.is_active),
 'pendingCount',(select count(*) from public.workspace_join_requests r where r.workspace_id=w.workspace_id and r.status='pending')) order by w.created_at desc),'[]'::jsonb) from public.workspaces w where w.mentor_profile_id=m);
end $$;
create or replace function public.get_workspace_details(p_workspace_id uuid) returns jsonb language plpgsql stable security definer set search_path='' as $$
declare w public.workspaces;
begin
 if not baya_private.owns_workspace(p_workspace_id) then raise exception 'unauthorized' using errcode='42501'; end if;
 select * into w from public.workspaces where workspace_id=p_workspace_id;
 return to_jsonb(w)||jsonb_build_object('learnerCount',(select count(*) from public.workspace_memberships where workspace_id=p_workspace_id and is_active),
 'pendingCount',(select count(*) from public.workspace_join_requests where workspace_id=p_workspace_id and status='pending'));
end $$;
revoke all on function public.request_workspace_join(text),public.list_my_join_requests(),public.list_workspace_join_requests(uuid),public.review_workspace_join_request(uuid,text) from public,anon;
grant execute on function public.request_workspace_join(text),public.list_my_join_requests(),public.list_workspace_join_requests(uuid),public.review_workspace_join_request(uuid,text) to authenticated;
commit;
