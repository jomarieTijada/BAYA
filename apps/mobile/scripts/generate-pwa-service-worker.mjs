import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputRoot = path.resolve(appRoot, process.env.BAYA_WEB_OUTPUT_DIR ?? 'dist');
const modelPath = '/models/baya/Baybayin_EfficientNetB0_BiLSTM_1.1.onnx';
const ortPaths = [
  '/ort/ort-wasm-runtime.min.js',
  '/ort/ort-wasm-simd-threaded.mjs',
  '/ort/ort-wasm-simd-threaded.wasm',
];

function localPath(url) {
  const parsed = new URL(url, 'https://baya.invalid');
  if (parsed.origin !== 'https://baya.invalid') throw new Error(`Cross-origin PWA entry asset: ${url}`);
  return parsed.pathname;
}

function isExcludedMedia(filePath) {
  const normalized = filePath.toLowerCase();
  return (
    normalized.endsWith('.mp4') ||
    normalized.endsWith('.webm') ||
    normalized.endsWith('.ogg') ||
    normalized.includes('/videos/') ||
    normalized.includes('media/videos')
  );
}

async function exportedFiles(directory) {
  const absolute = path.join(outputRoot, directory);
  const paths = [];
  for (const entry of await readdir(absolute, { withFileTypes: true })) {
    const child = path.posix.join(directory, entry.name);
    if (entry.isDirectory()) paths.push(...await exportedFiles(child));
    else if (entry.isFile() && !isExcludedMedia(child)) paths.push(`/${child}`);
  }
  return paths;
}

async function buildServiceWorker() {
  const html = await readFile(path.join(outputRoot, 'index.html'), 'utf8');
  const scripts = [...html.matchAll(/<script\b[^>]*\bsrc=["']([^"']+)["']/gi)].map(match => localPath(match[1]));
  const styles = [...html.matchAll(/<link\b(?=[^>]*\brel=["']stylesheet["'])[^>]*\bhref=["']([^"']+)["']/gi)]
    .map(match => localPath(match[1]));
  if (scripts.length === 0) throw new Error('Web export has no entry script to cache.');

  const precache = [...new Set([
    '/', '/manifest.json', '/favicon.ico', '/icon-192.png', '/icon-512.png',
    modelPath, ...ortPaths, ...scripts, ...styles,
    ...await exportedFiles('_expo/static/js/web'),
    ...await exportedFiles('assets'),
  ])];
  const digest = createHash('sha256');
  digest.update(await readFile(fileURLToPath(import.meta.url)));
  for (const url of precache) {
    const file = path.join(outputRoot, url === '/' ? 'index.html' : url.slice(1));
    digest.update(url);
    digest.update(await readFile(file));
  }
  const cacheName = `baya-pwa-${digest.digest('hex').slice(0, 16)}`;
  const source = `/* Generated by scripts/generate-pwa-service-worker.mjs. */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precache)};
const ML_URLS = new Set(${JSON.stringify([modelPath, ...ortPaths])});

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    try {
      for (const url of PRECACHE_URLS) {
        const response = await fetch(new Request(url, { cache: 'reload' }));
        if (!response.ok) throw new Error('PWA precache failed: ' + url + ' (' + response.status + ')');
        await cache.put(url, response);
      }
      await self.skipWaiting();
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith('baya-pwa-') && name !== CACHE_NAME) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname === '/sw.js') return;

  event.respondWith((async () => {
    const isNavigation = request.mode === 'navigate';
    const isMlOrStatic = ML_URLS.has(url.pathname) || url.pathname.startsWith('/_expo/static/');

    if (isMlOrStatic) {
      const cache = await caches.open(CACHE_NAME);
      const cached = await cache.match(request);
      if (cached) return cached;
    }

    try {
      const response = await fetch(request);
      if (isNavigation && !response.ok) {
        const cache = await caches.open(CACHE_NAME);
        const shell = (await cache.match('/')) || (await caches.match('/'));
        if (shell) return shell;
      }
      if (response.ok) {
        const cache = await caches.open(CACHE_NAME);
        await cache.put(isNavigation ? '/' : request, response.clone());
      }
      return response;
    } catch (error) {
      if (isNavigation) {
        const cache = await caches.open(CACHE_NAME);
        const shell = (await cache.match('/')) || (await caches.match('/'));
        if (shell) return shell;
        return new Response(
          '<!DOCTYPE html><html><head><meta charset="utf-8"><title>BAYA</title><meta name="viewport" content="width=device-width,initial-scale=1"></head><body style="background:#0b1120;color:#fff;font-family:sans-serif;display:flex;align-items:center;justify-content:center;height:100vh;margin:0;padding:24px;text-align:center"><div><h2 style="margin-bottom:8px">BAYA is currently offline</h2><p style="color:#94a3b8;margin-bottom:20px">Please reconnect or reload once online.</p><button onclick="location.reload()" style="padding:10px 20px;border-radius:8px;border:none;background:#f59e0b;color:#000;font-weight:bold;cursor:pointer">Reload</button></div></body></html>',
          { status: 200, headers: { 'Content-Type': 'text/html; charset=utf-8' } }
        );
      }

      const cache = await caches.open(CACHE_NAME);
      const cached = (await cache.match(request)) || (await caches.match(request));
      if (cached) return cached;

      return new Response('Resource unavailable offline', {
        status: 504,
        statusText: 'Gateway Timeout',
      });
    }
  })());
});
`;
  return { cacheName, precache, source };
}

const { cacheName, precache, source } = await buildServiceWorker();
const destination = path.join(outputRoot, 'sw.js');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== source) throw new Error('PWA service worker is missing or stale.');
  process.stdout.write(`[BAYA PWA] Verified ${cacheName} with ${precache.length} precached assets.\n`);
} else {
  await writeFile(destination, source);
  process.stdout.write(`[BAYA PWA] Wrote ${destination} (${cacheName}; ${precache.length} assets).\n`);
}
