import { createHash } from 'node:crypto';
import { readFile, readdir, stat, writeFile, unlink, realpath } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputRoot = path.resolve(appRoot, process.env.BAYA_WEB_OUTPUT_DIR ?? 'dist');
const activeModel = JSON.parse(await readFile(path.join(appRoot, 'ml/bayaActiveModel.json'), 'utf8'));
const modelPath = activeModel.modelUrl;
const metadataPaths = [activeModel.labelsUrl, activeModel.contractUrl];
const ortPaths = [
  '/ort/ort-wasm-runtime.min.js',
  '/ort/ort-wasm-simd-threaded.mjs',
  '/ort/ort-wasm-simd-threaded.wasm',
];

function localPath(url) {
  const parsed = new URL(url, 'https://baya.invalid');
  if (parsed.origin !== 'https://baya.invalid') throw new Error(`Cross-origin PWA entry asset: ${url}`);
  return parsed.pathname;
}

function isExcludedMedia(filePath) {
  const normalized = filePath.toLowerCase();
  return (
    normalized.endsWith('.mp4') ||
    normalized.endsWith('.webm') ||
    normalized.endsWith('.ogg') ||
    normalized.includes('/videos/') ||
    normalized.includes('media/videos')
  );
}

async function exportedFiles(directory, includeMedia = false) {
  const absolute = path.join(outputRoot, directory);
  const paths = [];
  for (const entry of await readdir(absolute, { withFileTypes: true })) {
    const child = path.posix.join(directory, entry.name);
    if (entry.isDirectory()) paths.push(...await exportedFiles(child, includeMedia));
    else if (entry.isFile() && (includeMedia || !isExcludedMedia(child))) paths.push(`/${child}`);
  }
  return paths;
}

async function buildServiceWorker() {
  // Expo copies public research candidates too. Ship only the selected model
  // and its metadata; preserve all source/research artifacts outside dist.
  const modelDirectory = path.join(outputRoot, 'models/baya');
  const resolvedOutput = await realpath(outputRoot);
  const resolvedModels = await realpath(modelDirectory);
  if (!resolvedModels.startsWith(resolvedOutput + path.sep) || resolvedOutput === await realpath(path.join(appRoot, 'public'))) {
    throw new Error('Refusing to prune model files outside the export directory.');
  }
  const selectedFiles = new Set([modelPath, ...metadataPaths].map(url => path.basename(url)));
  for (const entry of await readdir(modelDirectory, { withFileTypes: true })) {
    if (entry.isFile() && /\.(onnx|json)$/.test(entry.name) && !selectedFiles.has(entry.name)) {
      if (process.argv.includes('--check')) throw new Error(`Unselected model artifact in export: ${entry.name}`);
      await unlink(path.join(resolvedModels, entry.name));
    }
  }
  const html = await readFile(path.join(outputRoot, 'index.html'), 'utf8');
  const scripts = [...html.matchAll(/<script\b[^>]*\bsrc=["']([^"']+)["']/gi)].map(match => localPath(match[1]));
  const styles = [...html.matchAll(/<link\b(?=[^>]*\brel=["']stylesheet["'])[^>]*\bhref=["']([^"']+)["']/gi)]
    .map(match => localPath(match[1]));
  if (scripts.length === 0) throw new Error('Web export has no entry script to cache.');

  const assets = await exportedFiles('assets', true);
  const songAssets = assets.filter(url => /\/baybayin-song\.[^.]+\.mp4$/i.test(url));
  if (songAssets.length !== 1 ||
      (await stat(path.join(outputRoot, songAssets[0].slice(1)))).size === 0) {
    throw new Error('Web export must contain one nonempty hashed baybayin-song MP4 asset.');
  }

  const precache = [...new Set([
    '/', '/manifest.json', '/favicon.ico', '/icon-192.png', '/icon-512.png',
    modelPath, ...metadataPaths, ...ortPaths, ...scripts, ...styles,
    ...await exportedFiles('_expo/static/js/web'),
    ...assets.filter(url => !isExcludedMedia(url)),
  ])];
  const digest = createHash('sha256');
  digest.update(await readFile(fileURLToPath(import.meta.url)));
  for (const url of precache) {
    const file = path.join(outputRoot, url === '/' ? 'index.html' : url.slice(1));
    digest.update(url);
    digest.update(await readFile(file));
  }
  const cacheName = `baya-pwa-${digest.digest('hex').slice(0, 16)}`;
  const source = `/* Generated by scripts/generate-pwa-service-worker.mjs. */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precache)};
const ML_URLS = new Set(${JSON.stringify([modelPath, ...metadataPaths, ...ortPaths])});

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    try {
      for (const url of PRECACHE_URLS) {
        const response = await fetch(new Request(url, { cache: 'reload' }));
        if (!response.ok) throw new Error('PWA precache failed: ' + url + ' (' + response.status + ')');
        await cache.put(url, response);
      }
      await self.skipWaiting();
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith('baya-pwa-') && name !== CACHE_NAME) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname === '/sw.js') return;

  // 1. VIDEO & STREAMING MEDIA (RANGE REQUESTS):
  // Let the browser handle media streaming directly from Netlify.
  // CacheStorage explicitly throws on 206 responses, and returning full 200 responses
  // to Range requests breaks media seeking. Bypassing event.respondWith allows native
  // media engine Range handling with 206 Partial Content.
  const isMedia =
    request.destination === 'video' ||
    request.destination === 'audio' ||
    /\\.(?:mp4|webm|m4v|mov|ogg|mp3|wav)$/i.test(url.pathname) ||
    request.headers.has('range');

  if (isMedia) {
    return;
  }

  // 2. SPA NAVIGATION & DOCUMENT REQUESTS:
  // Identified by request.mode === 'navigate', request.destination === 'document',
  // or Accept header including text/html.
  const isNavigation =
    request.mode === 'navigate' ||
    request.destination === 'document' ||
    (request.headers.get('accept') && request.headers.get('accept').includes('text/html'));

  if (isNavigation) {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.ok) {
          caches.open(CACHE_NAME).then(cache => {
            cache.put('/', response.clone()).catch(() => {});
          }).catch(() => {});
          return response;
        }
      } catch (networkError) {
        // Network unavailable (offline)
      }

      // Fallback: cached SPA shell ('/')
      const cache = await caches.open(CACHE_NAME);
      const shell = (await cache.match('/')) || (await caches.match('/'));
      if (shell) return shell;

      // Safe offline HTML fallback: never return a 504 or error response for navigation
      return new Response(
        '<!DOCTYPE html><html><head><meta charset=\"utf-8\"><title>BAYA</title><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\"></head><body style=\"background:#0b1120;color:#fff;font-family:sans-serif;display:flex;align-items:center;justify-content:center;height:100vh;margin:0;padding:24px;text-align:center\"><div><h2 style=\"margin-bottom:8px\">BAYA is currently offline</h2><p style=\"color:#94a3b8;margin-bottom:20px\">Please reconnect or reload once online.</p><button onclick=\"location.reload()\" style=\"padding:10px 20px;border-radius:8px;border:none;background:#f59e0b;color:#000;font-weight:bold;cursor:pointer\">Reload</button></div></body></html>',
        { status: 200, headers: { 'Content-Type': 'text/html; charset=utf-8' } }
      );
    })());
    return;
  }

  // 3. STATIC APPLICATION ASSETS (ML models, ORT WASM, JS chunks, CSS, Icons, Fonts):
  // Cache-first for performance and offline reliability.
  const isStaticAsset =
    ML_URLS.has(url.pathname) ||
    url.pathname.startsWith('/_expo/static/') ||
    url.pathname.startsWith('/assets/') ||
    /\\.(?:js|mjs|wasm|onnx|css|png|jpg|jpeg|gif|webp|svg|ico|ttf|woff2?|json)$/i.test(url.pathname);

  if (isStaticAsset) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      const cached = (await cache.match(request)) || (await caches.match(request));
      if (cached) return cached;

      try {
        const response = await fetch(request);
        if (response.ok && response.status === 200) {
          cache.put(request, response.clone()).catch(() => {});
        }
        return response;
      } catch (error) {
        console.warn('[BAYA SW Asset Fetch Error]', {
          url: request.url,
          mode: request.mode,
          destination: request.destination,
          error: error instanceof Error ? error.message : String(error),
        });
        return new Response('Asset not found offline', { status: 404, statusText: 'Not Found' });
      }
    })());
    return;
  }

  // 4. ALL OTHER REQUESTS:
  // Network first with cache fallback
  event.respondWith((async () => {
    try {
      const response = await fetch(request);
      return response;
    } catch (error) {
      console.warn('[BAYA SW Fetch Error]', {
        url: request.url,
        mode: request.mode,
        error: error instanceof Error ? error.message : String(error),
      });
      const cache = await caches.open(CACHE_NAME);
      const cached = await cache.match(request);
      if (cached) return cached;
      return new Response('Network error', { status: 408, statusText: 'Request Timeout' });
    }
  })());
});
`;
  return { cacheName, precache, source };
}

const { cacheName, precache, source } = await buildServiceWorker();
const destination = path.join(outputRoot, 'sw.js');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== source) throw new Error('PWA service worker is missing or stale.');
  process.stdout.write(`[BAYA PWA] Verified ${cacheName} with ${precache.length} precached assets.\n`);
} else {
  await writeFile(destination, source);
  process.stdout.write(`[BAYA PWA] Wrote ${destination} (${cacheName}; ${precache.length} assets).\n`);
}
