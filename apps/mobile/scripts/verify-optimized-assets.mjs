import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const digest = bytes => createHash('sha256').update(bytes).digest('hex');

export async function verifyOptimizedAssets(repository = root) {
  const manifest = JSON.parse(await readFile(path.join(repository, 'scripts/optimization/mascot-derivatives.json'), 'utf8'));
  const registryPath = path.join(repository, 'apps/mobile/components/branding/baya/frameSources.ts');
  const canonical = await readFile(registryPath, 'utf8');
  const web = await readFile(registryPath.replace(/\.ts$/, '.web.ts'), 'utf8');
  const references = [...canonical.matchAll(/require\('([^']+\.png)'\)/g)].map(match => match[1]);
  const animation = JSON.parse(await readFile(path.join(repository, 'apps/mobile/assets/branding/baya/animations/v1.1/manifest.json'), 'utf8'));
  const expectedCount = Object.values(animation.sequences).reduce((count, sequence) => count + sequence.frameCount, 0);
  if (animation.version !== 'v1.1' || !expectedCount || references.length !== expectedCount || manifest.frames.length !== references.length) throw new Error('Mascot frame count differs from the v1.1 manifest.');
  for (const [state, sequence] of Object.entries(animation.sequences)) {
    const expectedReferences = sequence.frames.map((frame, index) => {
      if (frame.index !== index || frame.file !== `frame-${String(index).padStart(3, '0')}.png`) throw new Error('Invalid animation frame order.');
      return `../../../assets/branding/baya/animations/v1.1/${state}/${frame.file}`;
    });
    const actual = references.filter(reference => reference.includes(`/v1.1/${state}/`));
    if (sequence.frameCount !== expectedReferences.length || JSON.stringify(actual) !== JSON.stringify(expectedReferences)) throw new Error('Animation registry differs from the v1.1 manifest.');
  }
  let expected = '// Generated by scripts/optimization/optimize-images.py build; edit frameSources.ts.\n' + canonical;
  const remaining = new Map(manifest.frames.map(frame => [frame.source, frame]));
  if (remaining.size !== manifest.frames.length) throw new Error('Duplicate manifest source.');
  for (const reference of references) {
    const sourcePath = path.resolve(path.dirname(registryPath), reference);
    const source = path.relative(repository, sourcePath).split(path.sep).join('/');
    const frame = remaining.get(source);
    const output = source.replace('/branding/baya/', '/branding/baya-web/').replace(/\.png$/, '.webp');
    if (!frame || frame.output !== output || !output.startsWith('apps/mobile/assets/branding/baya-web/')) throw new Error(`Invalid derivative mapping: ${source}`);
    remaining.delete(source);
    if (digest(await readFile(sourcePath)) !== frame.source_sha256 ||
        digest(await readFile(path.join(repository, output))) !== frame.output_sha256) {
      throw new Error(`Stale mascot derivative: ${source}. Run python scripts/optimization/optimize-images.py build and verify.`);
    }
    expected = expected.replace(reference, reference.replace('/baya/', '/baya-web/').replace(/\.png$/, '.webp'));
  }
  // Accept platform line endings, but reject any changes to generated paths/order.
  if (remaining.size || web.replace(/\r\n/g, '\n') !== expected.replace(/\r\n/g, '\n')) throw new Error('Generated web frame registry is stale.');
  return manifest.frames.length;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`[BAYA assets] Verified ${await verifyOptimizedAssets()} lossless web derivatives.`);
}
